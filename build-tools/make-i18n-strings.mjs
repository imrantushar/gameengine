#!/usr/bin/env node
/**
 * Writes assets/build/i18n-strings.js: every string the POT attributes to a
 * JavaScript file, as a plain __() / _x() / _n() / _nx() call.
 *
 * The admin bundle cannot be read by the string extractor that WP-CLI and
 * WordPress.org share — it stops at a `[...new Set(...)]` inside the bundled
 * router and skips the whole file. So no translation is ever keyed to
 * backend.js and every admin screen stays in English, however complete the
 * language pack is.
 *
 * @wordpress/i18n keys locale data by text domain, not by file. Loading the
 * translations for this one small, parseable file therefore makes every
 * __( '...', 'gameengine' ) in every bundle resolve. The path carries no
 * version, so the translation file it maps to survives a release.
 *
 * Usage: node build-tools/make-i18n-strings.mjs \
 *          --pot=languages/gameengine.pot --out=assets/build/i18n-strings.js --domain=gameengine
 */
import fs from 'node:fs';

const args = Object.fromEntries(
	process.argv.slice( 2 ).map( ( a ) => {
		const [ k, ...v ] = a.replace( /^--/, '' ).split( '=' );
		return [ k, v.join( '=' ) ];
	} )
);
for ( const required of [ 'pot', 'out', 'domain' ] ) {
	if ( ! args[ required ] ) {
		console.error( `Missing --${ required }` );
		process.exit( 1 );
	}
}

const unquote = ( s ) =>
	s.slice( 1, -1 ).replace( /\\(.)/g, ( _, c ) => ( { n: '\n', t: '\t', r: '\r' }[ c ] ?? c ) );

function parsePot( text ) {
	const entries = [];
	for ( const block of text.split( /\r?\n\s*\r?\n/ ) ) {
		const e = { comments: [], refs: [], ctxt: null, id: null, plural: null };
		let field = null;
		for ( const raw of block.split( /\r?\n/ ) ) {
			const line = raw.trim();
			if ( line.startsWith( '#.' ) ) e.comments.push( line.slice( 2 ).trim() );
			else if ( line.startsWith( '#:' ) ) e.refs.push( ...line.slice( 2 ).trim().split( /\s+/ ) );
			else if ( line.startsWith( 'msgctxt ' ) ) { field = 'ctxt'; e.ctxt = unquote( line.slice( 8 ) ); }
			else if ( line.startsWith( 'msgid_plural ' ) ) { field = 'plural'; e.plural = unquote( line.slice( 13 ) ); }
			else if ( line.startsWith( 'msgid ' ) ) { field = 'id'; e.id = unquote( line.slice( 6 ) ); }
			else if ( line.startsWith( 'msgstr' ) ) field = null;
			else if ( line.startsWith( '"' ) && field ) e[ field ] += unquote( line );
		}
		if ( e.id ) entries.push( e );
	}
	return entries;
}

const isJs = ( ref ) => /\.(m?js|jsx)(:\d+)?$/.test( ref );
const lit = ( s ) => JSON.stringify( s );
const domain = lit( args.domain );

const strings = parsePot( fs.readFileSync( args.pot, 'utf8' ) )
	.filter( ( e ) => e.refs.some( isJs ) )
	.sort( ( a, b ) => ( a.ctxt ?? '' ).localeCompare( b.ctxt ?? '' ) || a.id.localeCompare( b.id ) );

const lines = strings.map( ( e ) => {
	const note = e.comments.filter( ( c ) => /^translators:/i.test( c ) ).map( ( c ) => `\t/* ${ c.replace( /\*\//g, '* /' ) } */\n` ).join( '' );
	let call;
	if ( e.plural !== null && e.ctxt !== null ) call = `_nx( ${ lit( e.id ) }, ${ lit( e.plural ) }, 1, ${ lit( e.ctxt ) }, ${ domain } )`;
	else if ( e.plural !== null ) call = `_n( ${ lit( e.id ) }, ${ lit( e.plural ) }, 1, ${ domain } )`;
	else if ( e.ctxt !== null ) call = `_x( ${ lit( e.id ) }, ${ lit( e.ctxt ) }, ${ domain } )`;
	else call = `__( ${ lit( e.id ) }, ${ domain } )`;
	return `${ note }\t${ call };`;
} );

const out = `/**
 * Generated by build-tools/make-i18n-strings.mjs from ${ args.pot }. Do not edit.
 *
 * Never executed. It lists the JavaScript strings in a form the translation
 * tools can read, so the admin screens can be translated. See the script above
 * for why the bundle itself cannot serve that purpose.
 */
( function () {
	var __ = wp.i18n.__, _x = wp.i18n._x, _n = wp.i18n._n, _nx = wp.i18n._nx;
${ lines.join( '\n' ) }
} );
`;

fs.writeFileSync( args.out, out );
console.log( `${ args.out }: ${ strings.length } strings (${ Math.round( out.length / 1024 ) } KB)` );
